-- Ejecutar una sola vez en Supabase > SQL Editor.
-- Conserva disponibilidad_integrantes y agrega excepciones por fecha/periodo.
-- integrante_id se guarda como texto para ser compatible tanto si la PK actual
-- de integrantes es UUID como si es numérica; el cliente compara los IDs como texto.
create table if not exists public.excepciones_disponibilidad (
  id bigint generated by default as identity primary key,
  integrante_id text not null,
  fecha_inicio date not null,
  fecha_fin date not null,
  disponible boolean not null default false,
  motivo text,
  creado_en timestamptz not null default now(),
  constraint excepciones_disponibilidad_fechas_validas check (fecha_fin >= fecha_inicio)
);

create index if not exists idx_excepciones_disponibilidad_integrante_fechas
  on public.excepciones_disponibilidad (integrante_id, fecha_inicio, fecha_fin);

alter table public.excepciones_disponibilidad enable row level security;

drop policy if exists "Disponibilidad excepciones acceso app" on public.excepciones_disponibilidad;
create policy "Disponibilidad excepciones acceso app"
on public.excepciones_disponibilidad
for all
to anon, authenticated
using (true)
with check (true);
